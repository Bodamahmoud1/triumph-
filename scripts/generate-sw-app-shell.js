#!/usr/bin/env node
const { readFileSync, writeFileSync } = require('fs');

const html = readFileSync('index.html', 'utf8');
const assets = new Set(['./', './index.html']);

function addLocalAsset(value) {
  if (!value || /^(https?:|data:|#)/.test(value)) return;
  const clean = value.split('#')[0].split('?')[0].replace(/^\//, '');
  if (clean) assets.add(`./${clean}`);
}

for (const match of html.matchAll(/<link\b[^>]*\bhref=["']([^"']+)["'][^>]*>/gi)) {
  addLocalAsset(match[1]);
}
for (const match of html.matchAll(/<script\b[^>]*\bsrc=["']([^"']+)["'][^>]*>/gi)) {
  addLocalAsset(match[1]);
}

assets.add('./data/chemicals.json');
assets.add('./data/programs.json');

const fontMatch = html.match(/https:\/\/fonts\.googleapis\.com\/css2\?[^"']+/);
if (fontMatch) assets.add(fontMatch[0].replace(/&amp;/g, '&'));

const output = `// Generated by scripts/generate-sw-app-shell.js. Do not edit by hand.\nconst APP_SHELL = ${JSON.stringify([...assets], null, 2)};\n`;
writeFileSync('sw-app-shell.js', output);
console.log(`Generated sw-app-shell.js with ${assets.size} precache entries.`);
