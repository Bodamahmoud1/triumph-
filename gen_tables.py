def map_chem_class(name):
    n = name.lower()
    if '100' in n or '200' in n: return 'chem-green'
    if 'build' in n: return 'chem-blue'
    if 'sonril' in n: return 'chem-red'
    if 'hypo' in n: return 'chem-orange'
    if 'soft' in n: return 'chem-pink'
    if 'neutra' in n: return 'chem-darkred'
    return 'chem-default'

